#!/usr/bin/env node
/**
 * build-index.mjs — scans every components/<category>/<part>/part.json and
 * regenerates INDEX.md (human + model lookup table) and manifest.json (machine).
 *
 * Run:  node scripts/build-index.mjs   (from repo root)
 *
 * part.json contract (every part folder MUST have one):
 * {
 *   "name":        "Pinned Scroll Section",      // human title
 *   "slug":        "pinned-scroll-section",      // folder name, kebab-case
 *   "category":    "motion",                     // react | css | vanilla | motion
 *   "tier":        "showcase",                    // "showcase" (🏆) | "practical" (✅)
 *   "tags":        ["scroll","pin","gsap"],      // lowercase keywords for matching
 *   "description": "One sentence: what it is and when to reach for it.",
 *   "deps":        ["gsap"],                       // libraries needed, [] if none
 *   "files":       ["index.js","style.css"],     // source files (NOT part.json/preview.html/README.md)
 *   "usage":       "Short paste-in note."
 * }
 */
import { readdir, readFile, writeFile, stat } from "node:fs/promises";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const CATEGORIES = ["react", "css", "vanilla", "motion"];
const TIER_EMOJI = { showcase: "🏆", practical: "✅" };
const CATEGORY_LABEL = {
  react: "React + Tailwind",
  css: "CSS-only",
  vanilla: "Vanilla HTML/CSS/JS",
  motion: "GSAP / Scroll Motion",
};

async function exists(p) {
  try { await stat(p); return true; } catch { return false; }
}

async function collect() {
  const parts = [];
  for (const cat of CATEGORIES) {
    const catDir = join(ROOT, "components", cat);
    if (!(await exists(catDir))) continue;
    const entries = await readdir(catDir, { withFileTypes: true });
    for (const e of entries) {
      if (!e.isDirectory()) continue;
      const partFile = join(catDir, e.name, "part.json");
      if (!(await exists(partFile))) {
        console.warn(`⚠  ${cat}/${e.name} has no part.json — skipped`);
        continue;
      }
      const meta = JSON.parse(await readFile(partFile, "utf8"));
      meta.path = `components/${cat}/${e.name}`;
      meta.preview = (await exists(join(catDir, e.name, "preview.html")))
        ? `${meta.path}/preview.html` : null;
      parts.push(meta);
    }
  }
  parts.sort((a, b) =>
    a.category.localeCompare(b.category) || a.name.localeCompare(b.name));
  return parts;
}

function buildIndexMd(parts) {
  const total = parts.length;
  const byTier = parts.reduce((a, p) => (a[p.tier] = (a[p.tier] || 0) + 1, a), {});
  let md = `# INDEX — saltycodestudio-parts\n\n`;
  md += `> **Local model: read this file first.** Match the user's request to a row by \`tags\`,\n`;
  md += `> open that part's folder, read its \`README.md\`, then copy the source \`files\`.\n`;
  md += `> Do not invent components — reuse what's here.\n\n`;
  md += `**${total} parts** · 🏆 ${byTier.showcase || 0} showcase · ✅ ${byTier.practical || 0} practical\n\n`;
  md += `Tiers: 🏆 = bold / showcase-grade · ✅ = premium but production-safe\n\n`;

  for (const cat of CATEGORIES) {
    const rows = parts.filter((p) => p.category === cat);
    if (!rows.length) continue;
    md += `## ${CATEGORY_LABEL[cat]} (${rows.length})\n\n`;
    md += `| Part | Tier | Tags | What it's for | Path |\n`;
    md += `|------|------|------|---------------|------|\n`;
    for (const p of rows) {
      md += `| **${p.name}** | ${TIER_EMOJI[p.tier] || p.tier} | ${(p.tags || []).join(", ")} | ${p.description} | \`${p.path}\` |\n`;
    }
    md += `\n`;
  }
  md += `---\n_Generated by \`scripts/build-index.mjs\` — do not edit by hand; re-run after adding parts._\n`;
  return md;
}

const parts = await collect();
await writeFile(join(ROOT, "manifest.json"), JSON.stringify(parts, null, 2) + "\n");
await writeFile(join(ROOT, "INDEX.md"), buildIndexMd(parts));
console.log(`✓ Indexed ${parts.length} parts → INDEX.md + manifest.json`);
